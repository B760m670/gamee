package expo.modules.spiritchatcryptocore

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Where private key material lives on Android — the counterpart of
 * `KeychainStore.swift`, and deliberately the same shape: save, load,
 * delete, keyed by a short account name.
 *
 * Android has no Keychain, so the guarantee has to be assembled. The
 * secret itself is encrypted with AES-256-GCM, and the key that encrypts
 * it is generated *inside* the AndroidKeyStore and never leaves it: this
 * process can ask for encryption and decryption, but cannot read the key,
 * and neither can anything that later reads the file the ciphertext is
 * in. On a device with secure hardware the key is held there, which is as
 * close as this platform gets to what the iOS Keychain does.
 *
 * `setUnlockedDeviceRequired(true)` is the counterpart of iOS's
 * `kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly`, and chosen for the
 * same reason: identity keys must be usable while the app runs in the
 * background, so requiring an unlock *at that moment* would break
 * background delivery — but they should not be readable from a device
 * that has not been unlocked at all.
 *
 * What is deliberately not required is user authentication per use. A
 * messenger that demanded a fingerprint before decrypting each incoming
 * message would be unusable, and the threat it defends against — someone
 * holding an unlocked phone — is not one key storage can solve.
 */
internal class SecretStore(context: Context) {

  private val preferences =
    context.getSharedPreferences("com.spiritchat.cryptocore.identity", Context.MODE_PRIVATE)

  /** Stores `data` under `account`, replacing whatever was there. */
  fun save(account: String, data: ByteArray) {
    val cipher = Cipher.getInstance(TRANSFORMATION)
    cipher.init(Cipher.ENCRYPT_MODE, encryptionKey())
    val ciphertext = cipher.doFinal(data)

    // The IV is generated by the cipher, is not secret, and is needed to
    // decrypt — so it travels with the ciphertext rather than in a second
    // entry that could be lost or mismatched independently.
    val stored = cipher.iv + ciphertext
    preferences.edit()
      .putString(account, android.util.Base64.encodeToString(stored, android.util.Base64.NO_WRAP))
      .apply()
  }

  /**
   * Returns `null` when nothing was stored under `account` — the same
   * "not found is not a failure" contract the iOS side has.
   *
   * A stored entry that cannot be decrypted is a different matter and
   * throws. It means the KeyStore key is gone while the ciphertext
   * remains, which happens for real: the user changed the lock screen in
   * a way that invalidated keys, or restored the app's files onto another
   * device. Returning `null` there would read as "no identity yet" and
   * walk someone through creating a new one, silently abandoning the
   * account they still have the recovery phrase for.
   */
  fun load(account: String): ByteArray? {
    val encoded = preferences.getString(account, null) ?: return null
    val stored = android.util.Base64.decode(encoded, android.util.Base64.NO_WRAP)
    require(stored.size > IV_LENGTH) { "stored secret for $account is too short to contain its IV" }

    val cipher = Cipher.getInstance(TRANSFORMATION)
    cipher.init(
      Cipher.DECRYPT_MODE,
      encryptionKey(),
      GCMParameterSpec(TAG_LENGTH_BITS, stored, 0, IV_LENGTH),
    )
    return cipher.doFinal(stored, IV_LENGTH, stored.size - IV_LENGTH)
  }

  /** Not an error if there was nothing to remove. */
  fun delete(account: String) {
    preferences.edit().remove(account).apply()
  }

  fun contains(account: String): Boolean = preferences.contains(account)

  private fun encryptionKey(): SecretKey {
    val keyStore = KeyStore.getInstance(ANDROID_KEY_STORE).apply { load(null) }
    (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

    val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEY_STORE)
    val spec = KeyGenParameterSpec.Builder(
      KEY_ALIAS,
      KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
    )
      .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
      .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
      .setKeySize(256)

    // Added only where it exists — it arrived in API 28, and this module
    // builds against the Expo default of 24. Below that the key is still
    // non-exportable and hardware-held where there is hardware; what is
    // missing is the refusal to operate while the device has not been
    // unlocked since boot. Worth having where available and not worth
    // refusing to run without.
    if (android.os.Build.VERSION.SDK_INT >= android.os.Build.VERSION_CODES.P) {
      spec.setUnlockedDeviceRequired(true)
    }

    generator.init(spec.build())
    return generator.generateKey()
  }

  private companion object {
    const val ANDROID_KEY_STORE = "AndroidKeyStore"
    const val KEY_ALIAS = "com.spiritchat.cryptocore.identity.wrapping-key"
    const val TRANSFORMATION = "AES/GCM/NoPadding"
    const val IV_LENGTH = 12
    const val TAG_LENGTH_BITS = 128
  }
}
